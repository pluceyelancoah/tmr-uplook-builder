/* Dose Confirmation Report PDF — same layout and math breakdown as the Bovaer Dose Calculator
   (COM-BCAL src/web/src/utils/pdf-export.ts), filled from the parsed report. Needs window.jspdf. */
(function () {
"use strict";

const COLORS = {
  darkBlue: [0, 17, 73], primaryBlue: [0, 71, 171], charcoal: [28, 26, 26], white: [255, 255, 255],
  gray: [107, 114, 128], lightGray: [243, 244, 246], slate: [226, 232, 240], red: [239, 68, 68], bovaerGreen: [37, 114, 78],
};
const APP_NAME = "Bovaer Dose Calculator";
const n = (v, d = 0) => Number(v).toLocaleString("en-US", { maximumFractionDigits: d });
const n2 = v => Number(v).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const text = (pdf, c) => pdf.setTextColor(...c), draw = (pdf, c) => pdf.setDrawColor(...c), fill = (pdf, c) => pdf.setFillColor(...c);

function header(pdf, W, M, title, date, logo){
  fill(pdf, COLORS.white); pdf.rect(0, 0, W, 52, "F");
  if (logo){ const h = 16; pdf.addImage(logo.dataUrl, "PNG", M, 6, h * logo.aspect, h); }
  else { pdf.setFontSize(20); pdf.setFont("helvetica", "bold"); text(pdf, COLORS.charcoal); pdf.text(`${APP_NAME} By Elanco`, M, 18); }
  pdf.setFontSize(7); pdf.setFont("helvetica", "bold"); text(pdf, COLORS.gray); pdf.text("REPORT DATE", W - M, 26, { align: "right" });
  pdf.setFontSize(11); text(pdf, COLORS.darkBlue); pdf.text(date, W - M, 32, { align: "right" });
  pdf.setFontSize(15); pdf.text(title, M, 32);
  draw(pdf, COLORS.darkBlue); pdf.setLineWidth(0.5); pdf.line(M, 35, W - M, 35);
  return 39;
}

function keyValue(pdf, { M, y, CW, rows, labelW = 55, rowH = 7, head }){
  if (head){
    fill(pdf, COLORS.lightGray); draw(pdf, COLORS.slate); pdf.setLineWidth(0.3);
    pdf.rect(M, y, CW, 8, "FD"); pdf.line(M + labelW, y, M + labelW, y + 8);
    pdf.setFontSize(7); pdf.setFont("helvetica", "bold"); text(pdf, COLORS.gray);
    pdf.text(head[0], M + 4, y + 4.5); pdf.text(head[1], M + labelW + 5, y + 4.5);
    y += 8;
  }
  draw(pdf, COLORS.slate); pdf.setLineWidth(0.3); pdf.rect(M, y, CW, rows.length * rowH, "S");
  rows.forEach(([label, value], i) => {
    const ry = y + i * rowH, sub = label.startsWith("    ");
    fill(pdf, COLORS.lightGray); pdf.rect(M, ry, labelW, rowH, "F");
    draw(pdf, COLORS.slate);
    if (i) pdf.line(M, ry, M + CW, ry);
    pdf.line(M + labelW, ry, M + labelW, ry + rowH);
    pdf.setFontSize(7); pdf.setFont("helvetica", head ? "normal" : "bold"); text(pdf, head ? COLORS.charcoal : COLORS.gray);
    pdf.text(label.trim(), M + (sub ? 8 : 4), ry + rowH / 2 + 0.5);
    if (value){ pdf.setFont("helvetica", "bold"); text(pdf, COLORS.charcoal); pdf.text(value, M + labelW + 5, ry + rowH / 2 + 0.5); }
  });
  return y + rows.length * rowH;
}

function section(pdf, title, y, M, CW){
  y += 2;
  pdf.setFontSize(9); pdf.setFont("helvetica", "bold"); text(pdf, COLORS.darkBlue); pdf.text(title, M, y);
  draw(pdf, COLORS.darkBlue); pdf.setLineWidth(0.4); pdf.line(M, y + 2, M + CW, y + 2);
  return y + 6;
}

function footer(pdf, M, W, H){
  const fy = H - 10;
  draw(pdf, COLORS.darkBlue); pdf.setLineWidth(0.4); pdf.line(M, fy - 4, W - M, fy - 4);
  pdf.setFontSize(7); pdf.setFont("helvetica", "normal"); text(pdf, COLORS.gray);
  pdf.text(`Elanco ${APP_NAME} | For professional use only`, M, fy);
  pdf.text("Generated by TapFeed / TMR Tracker -> UpLook Sheet Builder", W - M, fy, { align: "right" });
}

function status(dose, min, max){
  if (dose < min) return { color: COLORS.red, text: "WARNING", sub: "Below Label" };
  if (dose > max) return { color: COLORS.red, text: "WARNING", sub: "Above Label" };
  return { color: COLORS.bovaerGreen, text: "ON TARGET", sub: `${min}-${max} mg/kg DM` };
}

function dosePanels(pdf, { y, M, CW, dose, st }){
  const gap = 4, lw = Math.round(CW * 0.58), rw = CW - lw - gap, h = 22, rx = M + lw + gap;
  draw(pdf, COLORS.slate); pdf.setLineWidth(0.5); pdf.roundedRect(M, y, lw, h, 2, 2, "S");
  pdf.setFontSize(7); pdf.setFont("helvetica", "bold"); text(pdf, COLORS.gray); pdf.text("CALCULATED FINAL DOSE", M + 6, y + 5);
  pdf.setFontSize(24); text(pdf, COLORS.darkBlue); const dt = dose.toFixed(2); pdf.text(dt, M + 6, y + 16);
  const tw = pdf.getTextWidth(dt); pdf.setFontSize(10); pdf.setFont("helvetica", "normal"); pdf.text("mg/kg DM", M + 6 + tw + 2, y + 16);
  fill(pdf, COLORS.lightGray); draw(pdf, COLORS.slate); pdf.roundedRect(rx, y, rw, h, 2, 2, "FD");
  pdf.setFontSize(7); pdf.setFont("helvetica", "bold"); text(pdf, COLORS.gray); pdf.text("STATUS", rx + 6, y + 5);
  pdf.setFontSize(14); text(pdf, st.color); pdf.text(st.text, rx + 6, y + 13);
  pdf.setFontSize(8); pdf.setFont("helvetica", "normal"); text(pdf, COLORS.gray); pdf.text(st.sub, rx + 6, y + 18);
  return y + h + 6;
}

// "From 9/1/2026 until 9/30/2026" -> "Sep 1, 2026 to Sep 30, 2026"
function testPeriod(dateRange){
  const m = (dateRange || "").match(/(\d{1,2})\/(\d{1,2})\/(\d{4})/g);
  if (!m || m.length < 2) return "Not specified";
  const f = s => { const [mo, d, y] = s.split("/").map(Number);
    return new Date(y, mo - 1, d).toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" }); };
  return `${f(m[0])} to ${f(m[1])}`;
}

function inputRows(calc){
  const rows = [];
  calc.sources.forEach((s, i) => {
    const multi = calc.sources.length > 1;
    rows.push([multi ? `Source ${i + 1} Ingredient Name` : "Ingredient Name", s.name]);
    rows.push(["Quantity Fed (As-Fed)", `${n(s.quantityLb)} lb (AF)`]);
    rows.push(["3-NOP Concentration (Bovaer product)", "10%"]);
    rows.push(["Inclusion % (Bovaer in blend)", `${n(s.inclusionPct, 4)}%`]);
    rows.push(["Effective 3-NOP Concentration", `${n(100000 * s.inclusionPct / 100)} mg/kg`]);
    if (s.nestedPct !== null) rows.push([`Nested @ ${n(s.nestedPct, 4)}% in Premix`, `${n(10 * s.nestedPct / 100, 4)} % (AF)`]);
  });
  rows.push(["Total Feed Delivered (Dry Matter)", `${n(calc.totalFeedLbDM)} lb (DM)`]);
  return rows;
}

function breakdownSteps(calc){
  const steps = [];
  calc.sources.forEach((s, i) => {
    let mgKg = 100000 * s.inclusionPct / 100;
    steps.push([`Source ${i + 1}: ${s.name}`, `${n(s.quantityLb)} lb`]);
    steps.push([`    10% 3-NOP @ ${n(s.inclusionPct, 4)}% in blend`, `${n(mgKg)} mg/kg`]);
    if (s.nestedPct !== null){ mgKg *= s.nestedPct / 100; steps.push([`    Nested @ ${n(s.nestedPct, 4)}% in premix`, `${n(mgKg)} mg/kg effective`]); }
    steps.push([`    = 3-NOP (${n(s.quantityLb * 0.45359237, 4)} kg x ${n(mgKg)} mg/kg)`, `${n(s.nopMg)} mg`]);
  });
  steps.push(["Total 3-NOP (A)", `${n(calc.totalNopMg)} mg`]);
  if (calc.sources.length > 1) steps.push([`    = ${calc.sources.map(s => n(s.nopMg)).join(" + ")}`, ""]);
  steps.push(["Total Feed Delivered (B)", `${n(calc.totalFeedLbDM)} lb`]);
  steps.push(["    ( Converted to kg DM )", `${n(calc.totalFeedKgDM, 2)} kg DM`]);
  steps.push(["Final Dose (A / B)", `${n(calc.totalNopMg)} / ${n(calc.totalFeedKgDM, 2)} = ${n2(calc.mgPerKg)} mg/kg DM`]);
  return steps;
}

async function build(data, info){
  const calc = data.calculator;
  const { jsPDF } = window.jspdf;
  const pdf = new jsPDF("p", "mm", "a4");
  const W = pdf.internal.pageSize.getWidth(), H = pdf.internal.pageSize.getHeight(), M = 15, CW = W - 2 * M, maxY = H - 20;
  const date = new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });

  let y = header(pdf, W, M, "DOSE CONFIRMATION REPORT", date, window.BOVAER_LOGO);
  y = keyValue(pdf, { M, y, CW, rows: [["DAIRY NAME", info.farm || "Not specified"], ["REPRESENTATIVE", "Not specified"],
    ["TEST PERIOD", testPeriod(data.dateRange)]] });
  y = dosePanels(pdf, { y: y + 4, M, CW, dose: calc.mgPerKg, st: status(calc.mgPerKg, calc.labelMin, calc.labelMax) });

  y = section(pdf, "INPUT VERIFICATION", y, M, CW);
  y = keyValue(pdf, { M, y, CW, rows: inputRows(calc), labelW: 85, head: ["PARAMETER", "VALUE PROVIDED"] }) + 6;

  const steps = breakdownSteps(calc);
  if (y + 16 + 8 + steps.length * 7 > maxY){ footer(pdf, M, W, H); pdf.addPage(); y = 20; }
  y = section(pdf, "CALCULATION BREAKDOWN", y, M, CW);
  keyValue(pdf, { M, y, CW, rows: steps, labelW: 85, head: ["CALCULATION STEP", "VALUE"] });

  footer(pdf, M, W, H);
  return pdf;
}

async function download(data, info, baseName){
  if (!data.calculator || !window.jspdf) return false;
  const pdf = await build(data, info);
  pdf.save(baseName.replace(/^UpLook_Ingredient_Upload_/, "Bovaer_Dose_Report_") + ".pdf");
  return true;
}

window.TMRPdf = { build, download, inputRows, breakdownSteps };
})();
